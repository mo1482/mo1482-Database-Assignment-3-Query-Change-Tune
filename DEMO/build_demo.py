# ---------- query helpers ----------
def explain(sql, params=()):
    return [tuple(r) for r in con.execute("EXPLAIN QUERY PLAN " + sql, params).fetchall()]

def run_timed(sql, params=()):
    t0=time.perf_counter()
    cur=con.execute(sql, params)
    rows=cur.fetchall()
    elapsed=(time.perf_counter()-t0)*1000
    return rows, elapsed

