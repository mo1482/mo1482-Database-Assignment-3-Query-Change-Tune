def draw_code(d, x, y, lines, max_width, line_h=22, color=DARK, fnt=F_MONO_SMALL):
    for line in lines:
        # Preserve indentation and split only if very long.
        parts = textwrap.wrap(str(line), width=max(20, int(max_width/9)), subsequent_indent="    ", replace_whitespace=False, drop_whitespace=False) or [""]
        for p in parts:
            d.text((x,y), p, font=fnt, fill=color)
            y += line_h
    return y


